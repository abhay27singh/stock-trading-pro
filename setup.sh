#!/bin/bash
# One-time setup for a fresh clone: creates .env, the Python virtualenv and the
# frontend's node_modules, then checks the tools the stack needs.
#
# Safe to re-run — it never overwrites an existing .env and skips work already done.
#
# Usage:  ./setup.sh      then:  ./start-all.sh
set -u

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

green() { printf "\033[32m%s\033[0m\n" "$1"; }
yellow() { printf "\033[33m%s\033[0m\n" "$1"; }
red() { printf "\033[31m%s\033[0m\n" "$1"; }
step() { printf "\n\033[1m== %s\033[0m\n" "$1"; }

fail=0

# ---------------------------------------------------------------- prerequisites
step "Checking prerequisites"

find_jdk21() {
  # Honour an existing JDK 21 JAVA_HOME first, then the usual Homebrew locations
  # (Apple Silicon and Intel differ), then macOS java_home, then whatever is on PATH.
  if [ -n "${JAVA_HOME:-}" ] && "$JAVA_HOME/bin/java" -version 2>&1 | grep -q '"21'; then
    echo "$JAVA_HOME"; return 0
  fi
  for c in /opt/homebrew/opt/openjdk@21 /usr/local/opt/openjdk@21 /usr/lib/jvm/java-21-openjdk; do
    [ -x "$c/bin/java" ] && { echo "$c"; return 0; }
  done
  if command -v /usr/libexec/java_home >/dev/null 2>&1; then
    /usr/libexec/java_home -v 21 2>/dev/null && return 0
  fi
  return 1
}

if JDK21="$(find_jdk21)"; then
  green "  ✓ Java 21 found at $JDK21"
else
  red   "  ✗ Java 21 not found. Install it:  brew install openjdk@21"
  fail=1
fi

if command -v node >/dev/null 2>&1; then
  green "  ✓ Node $(node -v)"
else
  red   "  ✗ Node.js not found (18+ required):  brew install node"
  fail=1
fi

if command -v python3 >/dev/null 2>&1; then
  green "  ✓ $(python3 --version)"
else
  red   "  ✗ Python 3 not found:  brew install python"
  fail=1
fi

if command -v mysql >/dev/null 2>&1; then
  green "  ✓ MySQL client found"
else
  red   "  ✗ MySQL not found:  brew install mysql && brew services start mysql"
  fail=1
fi

[ "$fail" -eq 1 ] && { red "\nInstall the missing tools above, then re-run ./setup.sh"; exit 1; }

# ------------------------------------------------------------------------- .env
step "Configuring .env"

if [ -f "$ROOT/.env" ]; then
  yellow "  .env already exists — leaving it untouched."
else
  # Generated per-install so no secret is ever shared or committed.
  JWT="$(openssl rand -hex 32)"
  KEY="$(openssl rand -hex 32)"

  echo "  The services need your local MySQL password (input hidden)."
  printf "  MySQL user [root]: "
  read -r DB_USER
  DB_USER="${DB_USER:-root}"
  printf "  MySQL password for '%s': " "$DB_USER"
  read -rs DB_PASS
  echo

  if [ -z "$DB_PASS" ]; then
    red "  ✗ Password cannot be empty — the services have no fallback and will not start."
    exit 1
  fi

  cat > "$ROOT/.env" <<EOF
# Local secrets — gitignored, never commit. Generated by setup.sh.

# --- Database ---
DB_USERNAME=$DB_USER
DB_PASSWORD=$DB_PASS

# --- JWT (shared HMAC secret across all services; HS256 needs >= 32 bytes) ---
JWT_SECRET=$JWT
JWT_EXPIRATION=86400000

# --- Service-to-service (internal wallet) shared key ---
INTERNAL_API_KEY=$KEY

# --- Python market-data + prediction service ---
PREDICTION_SERVICE_URL=http://localhost:5001
MARKET_POLL_RATE=10000

CORS_ALLOWED_ORIGINS=http://localhost:3002
EOF
  chmod 600 "$ROOT/.env"
  green "  ✓ .env created (JWT + internal key generated randomly)"

  if mysqladmin ping -u"$DB_USER" -p"$DB_PASS" --silent 2>/dev/null; then
    green "  ✓ MySQL accepted those credentials"
  else
    yellow "  ⚠ Could not reach MySQL with those credentials. Check it is running:"
    yellow "     brew services start mysql"
  fi
fi

# --------------------------------------------------------------- python virtualenv
step "Python environment"

if [ -x "$ROOT/python/venv/bin/python" ]; then
  yellow "  venv already exists — checking dependencies."
else
  python3 -m venv "$ROOT/python/venv" || { red "  ✗ Could not create virtualenv"; exit 1; }
  green "  ✓ virtualenv created"
fi

"$ROOT/python/venv/bin/pip" install -q --disable-pip-version-check -r "$ROOT/python/requirements.txt" \
  && green "  ✓ Python dependencies installed" \
  || { red "  ✗ pip install failed"; exit 1; }

# ------------------------------------------------------------------ frontend deps
step "Frontend dependencies"

if [ -d "$ROOT/frontend/node_modules" ]; then
  yellow "  node_modules already present — skipping npm install."
else
  ( cd "$ROOT/frontend" && npm install --no-audit --no-fund ) \
    && green "  ✓ npm dependencies installed" \
    || { red "  ✗ npm install failed"; exit 1; }
fi

# ------------------------------------------------------------------------- done
step "Setup complete"
echo "  Start everything:  ./start-all.sh"
echo "  Then open:         http://localhost:3002"
echo "  Stop everything:   ./stop-all.sh"
echo
echo "  Register an account in the app to start trading. To grant yourself admin:"
echo "    mysql -u<user> -p auth_db -e \"UPDATE users SET role='ADMIN' WHERE email='you@example.com';\""
echo "  then log out and back in."
